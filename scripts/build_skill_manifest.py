#!/usr/bin/env python3
"""Generate and verify skills/manifest.json — the single source of truth for the
pipeline version and for the exact bytes of each skill file.

The pipeline generation number ("v29") lives in this manifest and nowhere else that
can drift silently: skill filenames carry no version, and every skill description
must quote the manifest's version. Repository releases are versioned separately, by
git tag (semver); that number is deliberately not duplicated into any file.

Usage:
  python scripts/build_skill_manifest.py              # regenerate (keeps the version)
  python scripts/build_skill_manifest.py --check      # verify; non-zero exit on drift
  python scripts/build_skill_manifest.py --set-version 30
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILL_DIR = ROOT / "skills"
MANIFEST = SKILL_DIR / "manifest.json"
DESCRIPTION_PREFIX = "Expert Review Pipeline v{v} (ComputationalReviewTemplate):"


def frontmatter_field(text, field):
    m = re.search(r"^" + field + r":\s*(.*)$", text, re.M)
    if not m:
        return None
    return m.group(1).strip().strip('"')


def skill_files():
    return sorted(p for p in SKILL_DIR.glob("*.md"))


def build(version):
    skills = []
    for p in skill_files():
        raw = p.read_bytes()
        text = raw.decode("utf-8")
        skills.append({
            "name": frontmatter_field(text, "name") or p.stem,
            "file": "skills/" + p.name,
            "bytes": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
        })
    return {
        "_comment": "Generated by scripts/build_skill_manifest.py; CI verifies it. "
                    "Do not edit by hand.",
        "pipeline_version": version,
        "skill_count": len(skills),
        "skills": skills,
    }


def load_manifest():
    if not MANIFEST.exists():
        sys.exit("manifest.json not found; run without --check to generate it")
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def check():
    man = load_manifest()
    version = man["pipeline_version"]
    prefix = DESCRIPTION_PREFIX.format(v=version)
    failures = []

    listed = {s["file"]: s for s in man["skills"]}
    on_disk = {"skills/" + p.name: p for p in skill_files()}

    missing = sorted(set(listed) - set(on_disk))
    extra = sorted(set(on_disk) - set(listed))
    if missing:
        failures.append(("SKILL_SET", "listed in manifest but absent: " + ", ".join(missing)))
    if extra:
        failures.append(("SKILL_SET", "present on disk but unlisted: " + ", ".join(extra)))
    if man["skill_count"] != len(man["skills"]):
        failures.append(("SKILL_COUNT", "skill_count {} != {} entries".format(
            man["skill_count"], len(man["skills"]))))

    for path in sorted(set(listed) & set(on_disk)):
        raw = on_disk[path].read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        if digest != listed[path]["sha256"]:
            failures.append(("SKILL_HASHES", path + " changed without a manifest regen"))
        elif len(raw) != listed[path]["bytes"]:
            failures.append(("SKILL_HASHES", path + " byte count disagrees with the manifest"))

        text = raw.decode("utf-8")
        name = frontmatter_field(text, "name")
        if name != on_disk[path].stem:
            failures.append(("NAME_MATCHES_FILENAME",
                             "{}: frontmatter name {!r} != filename stem".format(path, name)))
        description = frontmatter_field(text, "description") or ""
        if not description.startswith(prefix):
            failures.append(("DESCRIPTION_VERSION",
                             "{}: description does not start with {!r}".format(path, prefix)))

    for path in on_disk:
        if re.search(r"-v\d+\.md$", path):
            failures.append(("NO_VERSIONED_FILENAME",
                             path + ": the generation number belongs in the manifest, "
                                    "not in a filename"))

    readme = (ROOT / "README.md").read_text(encoding="utf-8")
    found = set(re.findall(r"Expert Review Pipeline v(\d+)", readme))
    if found and found != {str(version)}:
        failures.append(("README_VERSION",
                         "README names pipeline version(s) {} but the manifest says {}".format(
                             sorted(found), version)))

    if failures:
        print("manifest check FAILED ({} problem(s)):".format(len(failures)))
        for check_name, detail in failures:
            print("  [{}] {}".format(check_name, detail))
        return 1
    print("manifest check passed: {} skills, pipeline v{}".format(len(man["skills"]), version))
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify instead of writing")
    ap.add_argument("--set-version", metavar="N", help="bump the pipeline generation number")
    args = ap.parse_args()

    if args.check:
        if args.set_version:
            ap.error("--check and --set-version are mutually exclusive")
        return check()

    version = args.set_version or (load_manifest()["pipeline_version"]
                                   if MANIFEST.exists() else None)
    if version is None:
        ap.error("no existing manifest: pass --set-version N for the first generation")
    MANIFEST.write_text(json.dumps(build(str(version)), indent=2) + "\n", encoding="utf-8")
    print("wrote {} ({} skills, pipeline v{})".format(
        MANIFEST.relative_to(ROOT), len(skill_files()), version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
